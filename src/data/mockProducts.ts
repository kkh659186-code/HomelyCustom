// LocalStorage Persistence Helpers for Custom User Catalog Items
const CUSTOM_PRODUCTS_STORAGE_KEY = "homely_custom_products_catalog";

export function getStoredCustomProducts(): ProductItem[] {
  if (typeof window === "undefined") return [];
  try {
    const raw = localStorage.getItem(CUSTOM_PRODUCTS_STORAGE_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? parsed : [];
  } catch (err) {
    console.error("Failed to load custom products from localStorage:", err);
    return [];
  }
}

export function saveCustomProduct(product: ProductItem): void {
  if (typeof window === "undefined") return;
  try {
    const current = getStoredCustomProducts();
    const filtered = current.filter((p) => p.id !== product.id);
    const updated = [product, ...filtered];
    localStorage.setItem(CUSTOM_PRODUCTS_STORAGE_KEY, JSON.stringify(updated));
  } catch (err) {
    console.error("Failed to save custom product to localStorage:", err);
  }
}

export function deleteCustomProduct(productId: string): void {
  if (typeof window === "undefined") return;
  try {
    const current = getStoredCustomProducts();
    const updated = current.filter((p) => p.id !== productId);
    localStorage.setItem(CUSTOM_PRODUCTS_STORAGE_KEY, JSON.stringify(updated));
  } catch (err) {
    console.error("Failed to delete custom product from localStorage:", err);
  }
}

export function getAllProducts(): ProductItem[] {
  const custom = getStoredCustomProducts();
  return [...custom, ...MOCK_PRODUCTS];
}

export function getProductById(id: string): ProductItem | undefined {
  const all = getAllProducts();
  return all.find((p) => p.id === id);
}

